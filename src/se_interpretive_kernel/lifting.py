"""lifting.py - Comparison liftings from output regimes to object regimes.

Interpretation returns structured outputs, and comparing two outputs requires
an equivalence on the atomic values they are built from.
A *comparison lifting* carries an output regime up to the structures:

    C : Eq(O) -> Eq(X)

where ``O`` is the carrier of atomic outputs and ``X`` is the carrier of the
structured objects being compared.

The kernel construction requires ``C`` to preserve arbitrary meets.
Complete meet homomorphisms of this shape are exactly the ``Eq(O)``-valued
generalized ultrametrics on ``X``: every one of them is given by a cost

    delta : X x X -> Eq(O)

assigning to each pair the least output identification that would make the
two objects the same, with

    C(rho) = { (x, y) : delta(x, y) refines rho }.

The cost must satisfy three laws:

1. ``delta(x, x)`` is the discrete partition,
2. ``delta(x, y) == delta(y, x)``, and
3. ``delta(x, z)`` refines ``delta(x, y) join delta(y, z)``.

A lifting that satisfies them supports the adjunction.
A comparison that only claims to be a lifting does not, and
:func:`check_lifting_laws` is the finite test that separates the two cases.

Two comparisons in this module are present because they fail:

- :class:`QuotientImage` compares unordered outputs by equality of their
  quotient images. It is monotone but does not preserve meets, so no cost
  function represents it.
- :class:`OptimalMatching` looks like the natural cost for unordered outputs
  but violates the triangle law, because the meet over alternative bijections
  cannot be moved through the join in a lattice that is not distributive.

:class:`IndexedPointwise` is the comparison this package selects.
When the outputs are genuinely unordered, a declared canonicalization
supplies the index, and the price of that choice is a cost no finer than the
best matching would have required.
"""

from collections.abc import Callable, Sequence
from dataclasses import dataclass
from itertools import permutations
from typing import Protocol

from .partition import Item, Pair, Partition, meet_all

type Form = Callable[[Item], Sequence[Item]]
"""Map an object to the indexed sequence of atomic outputs it presents."""

type Members = Callable[[Item], frozenset[Item]]
"""Map an object to the unordered atomic outputs it contains."""


class Comparison(Protocol):
    """Carry an output regime up to a regime on structured objects."""

    @property
    def objects(self) -> tuple[Item, ...]:
        """Return the carrier of structured objects being compared."""
        ...

    def induced(self, rho: Partition) -> Partition:
        """Return the object regime induced by an output regime."""
        ...


class Lifting(Protocol):
    """Assign each pair of objects the least output regime identifying them."""

    @property
    def objects(self) -> tuple[Item, ...]:
        """Return the carrier of structured objects being compared."""
        ...

    @property
    def output_carrier(self) -> tuple[Item, ...]:
        """Return the carrier of atomic output values."""
        ...

    def cost(self, x: Item, y: Item) -> Partition:
        """Return the least output regime under which two objects agree."""
        ...

    def induced(self, rho: Partition) -> Partition:
        """Return the object regime induced by an output regime."""
        ...


@dataclass(frozen=True)
class _CostBased:
    """Provide the induced comparison shared by every cost-based lifting.

    Two objects are related under an output regime exactly when the cost of
    identifying them refines that regime.
    """

    def _induced_from_cost(
        self,
        objects: tuple[Item, ...],
        cost: Callable[[Item, Item], Partition],
        rho: Partition,
    ) -> Partition:
        """Return the object regime generated by pairs whose cost fits ``rho``.

        Only pairs are collected here.
        Their equivalence closure is taken by :meth:`Partition.from_pairs`,
        which is sound because the triangle law makes the relation transitive
        already when the laws hold, and because closing a relation that is
        already transitive changes nothing.
        """
        pairs: list[Pair] = [
            (x, y)
            for i, x in enumerate(objects)
            for y in objects[i + 1 :]
            if cost(x, y).refines(rho)
        ]
        return Partition.from_pairs(objects, pairs)


@dataclass(frozen=True)
class IndexedPointwise(_CostBased):
    """Compare objects position by position over a declared index.

    ``form`` presents each object as a sequence of atomic outputs.
    Two objects are compared by requiring agreement at every position, so the
    cost of identifying them is generated by the pairs of values standing at
    corresponding positions.

    This comparison preserves arbitrary meets, because agreement at every
    position is a conjunction of atomic comparisons and universal
    quantification commutes with meet.

    When the underlying outputs are unordered, ``form`` is a declared
    canonicalization and is part of the declaration rather than an
    implementation detail.
    A canonicalization that is not injective identifies distinct objects at
    zero cost, which declares an identity without ever appearing as a declared
    identity regime.

    Sequences compared here must already have equal length.
    Length mismatch is a declared comparison outcome and belongs to the
    tagged outcome domain, not to this module.
    """

    output_carrier: tuple[Item, ...]
    objects: tuple[Item, ...]
    form: Form

    def cost(self, x: Item, y: Item) -> Partition:
        """Return the closure of the pairs standing at corresponding positions."""
        left, right = self.form(x), self.form(y)
        if len(left) != len(right):
            msg = (
                "indexed comparison requires equal-length forms; "
                "length mismatch is a tagged outcome, not a comparison"
            )
            raise ValueError(msg)
        return Partition.from_pairs(self.output_carrier, zip(left, right, strict=True))

    def induced(self, rho: Partition) -> Partition:
        """Return the object regime induced by an output regime."""
        return self._induced_from_cost(self.objects, self.cost, rho)


@dataclass(frozen=True)
class OptimalMatching(_CostBased):
    """Compare unordered objects by the cheapest bijection between them.

    The cost is the meet, over all bijections between the two member sets, of
    the identification each bijection would require.
    This is the natural reading of "there is a matching under which the two
    agree", and it is the comparison a practitioner would reach for first.

    It is not a lifting.
    The triangle law fails, because moving the meet over alternative
    bijections through the join requires a distributivity the partition
    lattice does not have.
    :func:`check_lifting_laws` returns the counterexample.

    The class is retained because the failure is a result: optimal matching
    and meet preservation cannot be had together, and a declared
    canonicalization is the price of keeping the second.
    """

    output_carrier: tuple[Item, ...]
    objects: tuple[Item, ...]
    members: Members

    def cost(self, x: Item, y: Item) -> Partition:
        """Return the meet over all bijections of the cost each would require.

        Member sets of different sizes admit no bijection.
        The meet of an empty family is the top element, which reports that
        only the total identification makes the two objects agree.
        """
        left, right = (
            sorted(self.members(x), key=repr),
            sorted(self.members(y), key=repr),
        )
        if len(left) != len(right):
            return Partition.indiscrete(self.output_carrier)
        candidates = [
            Partition.from_pairs(self.output_carrier, zip(left, perm, strict=True))
            for perm in permutations(right)
        ]
        return meet_all(self.output_carrier, candidates)

    def induced(self, rho: Partition) -> Partition:
        """Return the object regime induced by an output regime."""
        return self._induced_from_cost(self.objects, self.cost, rho)


@dataclass(frozen=True)
class QuotientImage:
    """Compare unordered objects by equality of their quotient images.

    Two objects are related under an output regime when the sets of output
    classes they occupy are equal.

    This comparison is monotone: collapsing output classes further cannot
    separate objects whose images already agreed.
    It does not preserve meets, so it is not represented by any cost function
    and does not support the adjunction.
    :func:`check_meet_preservation` returns the counterexample.

    The obstruction is the existential matching hidden in comparing unordered
    images, not the fact that the outputs are sets.
    """

    output_carrier: tuple[Item, ...]
    objects: tuple[Item, ...]
    members: Members

    def image(self, x: Item, rho: Partition) -> frozenset[int]:
        """Return the set of output classes the object's members occupy."""
        return frozenset(rho.label_of(m) for m in self.members(x))

    def induced(self, rho: Partition) -> Partition:
        """Return the object regime relating objects with equal images."""
        return Partition.from_labels(
            self.objects, {x: self.image(x, rho) for x in self.objects}
        )


@dataclass(frozen=True)
class LawViolation:
    """Report one failed law together with the values that witness it.

    ``law`` names the law that failed.

    ``witness`` contains the objects or output regimes the failure was found
    on, in the order the law names them.

    ``detail`` states what was expected and what held instead.
    """

    law: str
    witness: tuple[Item, ...]
    detail: str


def check_lifting_laws(lifting: Lifting) -> tuple[LawViolation, ...]:
    """Return every violation of the three cost laws, with witnesses.

    Identity, symmetry, and the triangle law are checked over every ordered
    triple of objects.
    The carriers are finite and small by construction, so the check is
    exhaustive rather than sampled.

    An empty result means the cost is an ``Eq(O)``-valued generalized
    ultrametric, so the comparison it induces preserves arbitrary meets and
    the threshold construction applies to it.
    """
    objects = lifting.objects
    bottom = Partition.discrete(lifting.output_carrier)
    found: list[LawViolation] = []

    for x in objects:
        if lifting.cost(x, x) != bottom:
            found.append(
                LawViolation(
                    "identity",
                    (x,),
                    "cost of an object against itself is not the discrete partition",
                )
            )

    for i, x in enumerate(objects):
        for y in objects[i + 1 :]:
            if lifting.cost(x, y) != lifting.cost(y, x):
                found.append(
                    LawViolation("symmetry", (x, y), "cost depends on argument order")
                )

    for x in objects:
        for y in objects:
            for z in objects:
                direct = lifting.cost(x, z)
                detour = lifting.cost(x, y).join(lifting.cost(y, z))
                if not direct.refines(detour):
                    found.append(
                        LawViolation(
                            "triangle",
                            (x, y, z),
                            "direct cost is not refined by the cost through the "
                            "intermediate object",
                        )
                    )

    return tuple(found)


def check_meet_preservation(
    comparison: Comparison, samples: Sequence[Partition]
) -> tuple[LawViolation, ...]:
    """Return every failure of meet preservation over the sampled regimes.

    A comparison preserves meets when the regime induced by a meet of output
    regimes equals the meet of the regimes each induces separately.
    Failure means no cost function represents the comparison, so the
    threshold construction and the adjunction are both unavailable for it.
    """
    found: list[LawViolation] = []
    for i, rho in enumerate(samples):
        for sigma in samples[i + 1 :]:
            together = comparison.induced(rho.meet(sigma))
            apart = comparison.induced(rho).meet(comparison.induced(sigma))
            if together != apart:
                found.append(
                    LawViolation(
                        "meet-preservation",
                        (rho, sigma),
                        "the regime induced by the meet differs from the meet of "
                        "the induced regimes",
                    )
                )
    return tuple(found)


def check_monotonicity(
    comparison: Comparison, samples: Sequence[Partition]
) -> tuple[LawViolation, ...]:
    """Return every failure of monotonicity over the sampled regimes.

    Coarsening an output regime may only coarsen the regime it induces.
    Monotonicity is strictly weaker than meet preservation, and a comparison
    may satisfy it while still admitting no cost function.
    Reporting the two separately keeps that distinction visible.
    """
    found: list[LawViolation] = []
    for rho in samples:
        for sigma in samples:
            if rho.refines(sigma) and not comparison.induced(rho).refines(
                comparison.induced(sigma)
            ):
                found.append(
                    LawViolation(
                        "monotonicity",
                        (rho, sigma),
                        "a coarser output regime induced a strictly finer object "
                        "regime",
                    )
                )
    return tuple(found)
